from typing import Protocol


class CatalogStore(Protocol):
    def read(self, item_id: str, kind: str | None = None) -> dict: ...

    def put(
        self, kind, source, document, image=None, complete=False
    ) -> dict: ...
    def artists_named(self, name: str) -> list[dict]: ...


class MetadataPort(Protocol):
    async def fetch(self, payload: dict) -> dict: ...


class DocumentMapping(Protocol):
    def artist(self, row: dict) -> dict | None: ...
    def album(self, row: dict) -> dict | None: ...
    def song(self, row, album=None, position=None) -> dict | None: ...
    def remember_tops(self, artist: dict, row: dict) -> list[dict]: ...
    def radio(self, result: dict) -> list[dict]: ...
    def match_loved(self, rows: dict, artist: str, title: str) -> dict: ...

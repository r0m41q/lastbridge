from typing import Protocol


class CatalogAccess(Protocol):
    def read(self, item_id: str, kind: str | None = None) -> dict: ...
    async def detail(self, item_id: str, kind: str) -> dict: ...
    async def match_loved(self, artist: str, title: str) -> dict: ...


class LibraryAccess(Protocol):
    async def change(
        self, user_id: int, targets, enabled: bool, *, imported=None
    ) -> bool: ...


class SecretCipher(Protocol):
    def decrypt(self, value: str) -> str: ...


class SyncProvider(Protocol):
    @property
    def configured(self) -> bool: ...

    async def loved(
        self, target: str, page: int
    ) -> tuple[list[tuple[str, str]], int]: ...

    async def scrobble(
        self, secret: str, report: dict
    ) -> tuple[str, str | None]: ...

    async def set_love(self, secret: str, job: dict): ...


class SyncStore(Protocol):
    def linked(self, user_id: int) -> bool | None: ...
    def record(self, user: dict, values: dict, prepared: list, now: int): ...
    def control(self, user_id: int, action: str): ...
    def snapshot(self, user_id: int) -> tuple: ...
    def startup(self) -> list[dict]: ...
    def recover_delivery(self): ...
    def claim_delivery(self) -> tuple[dict, dict | None] | None: ...
    def invalidate(self, user: dict): ...
    def complete_delivery(self, job: dict, state: str, error: str | None): ...
    def claim_love(self) -> tuple[dict, dict | None] | None: ...
    def complete_love(self, job: dict, state: str, error: str | None): ...
    def recover_loves(self): ...
    def love_reports(self, user_id: int) -> list[dict]: ...
    def claim_import(self) -> tuple[dict, dict | None] | None: ...
    def save_page(self, job: dict, rows: list, total: int): ...
    def finish_import(self, job: dict): ...
    def fail_import(self, job: dict, now: float, error: Exception): ...
    def removed(self, user_id: int, key: str) -> bool: ...
    def is_active(self, job: dict) -> bool: ...

    def resolved(
        self,
        job: dict,
        item: dict,
        state: str,
        error: str | None,
        song_id: str | None,
    ): ...

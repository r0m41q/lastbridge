from typing import Protocol

from lastbridge.features.radio.domain.models import Exclusions


class CatalogAccess(Protocol):
    def read(self, item_id: str, kind: str | None = None) -> dict: ...
    async def detail(self, item_id: str, kind: str) -> dict: ...
    def song_by_source(self, source: str) -> dict: ...
    async def radio(self, source: str) -> list[dict]: ...
    async def match_loved(self, artist: str, title: str) -> dict: ...


class LibraryAccess(Protocol):
    def decorate(self, user_id: int, document): ...
    def recording(self, user_id: int, item_id: str, kind: str) -> dict: ...


class TasteProvider(Protocol):
    @property
    def configured(self) -> bool: ...

    async def taste_rows(
        self, method: str, **parameters
    ) -> list[tuple[str, str]]: ...


class RadioStore(Protocol):
    def snapshot(self, user: dict) -> dict | None: ...
    def publish(self, user: dict, seed: dict, songs: list[dict]): ...
    def exclusions(self, user: dict) -> Exclusions: ...
    def artist_song(self, item_id: str) -> str | None: ...

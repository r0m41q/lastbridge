from contextlib import AbstractContextManager
from typing import Protocol


class CatalogAccess(Protocol):
    def read(self, item_id: str, kind: str | None = None) -> dict: ...


class LibraryAccess(Protocol):
    def decorate(self, user_id: int, document): ...
    async def reconcile(self): ...
    def notify(self): ...


class MixAccess(Protocol):
    def playlists(self, user: dict, item_id: str | None = None): ...


class RadioAccess(Protocol):
    def playlist_id(self, user_id: int) -> str: ...
    def playlist(self, user: dict, detail: bool = False) -> dict | None: ...


class PlaylistEdit(Protocol):
    def row(self, user: dict, item_id: str) -> dict | None: ...
    def count(self, user_id: int) -> int: ...
    def insert(self, item_id: str, user_id: int, name: str, stamp: str): ...
    def rename(self, item_id: str, name: str, stamp: str): ...
    def ids(self, item_id: str) -> list[str]: ...
    def entries(self, item_id: str, ids: list[str]): ...
    def update(self, item_id: str, name: str, comment: str, stamp: str): ...
    def delete(self, item_id: str): ...
    def keep(self, item_id: str, enabled: bool, stamp: str): ...
    def schedule(self, user: dict): ...


class PlaylistStore(Protocol):
    def edit(self) -> AbstractContextManager[PlaylistEdit]: ...
    def local(self, user: dict) -> list[tuple[dict, list[str]]]: ...

    def get(
        self, user: dict, item_id: str
    ) -> tuple[dict, list[str]] | None: ...
    def downloaded(self, user: dict) -> set[str]: ...

from typing import Protocol

from lastbridge.features.playlists.domain.imports import Snapshot


class SnapshotProvider(Protocol):
    async def prepare(self, source: str, previous: dict) -> dict: ...
    async def batch(self, progress: dict) -> dict: ...


class ImportStore(Protocol):
    def visible(self, user: dict) -> list[dict]: ...
    def get(self, user: dict, item_id: str) -> dict: ...

    def enqueue(self, user: dict, source: str, shared: bool) -> str: ...
    def verify_lastfm_owner(self, job: dict): ...
    def queue(self, user: dict, offset: int, limit: int) -> list[dict]: ...
    def request(self, item_id: str): ...

    def decide(
        self,
        user: dict,
        item_id: str,
        source_key: str,
        song_id: str,
        acknowledge: bool,
        action: str = "choose",
        undo: str = "",
    ): ...
    def control(self, user: dict, item_id: str, action: str): ...
    def checkpoint(self, job: dict, progress: dict) -> bool: ...
    def release(self, job: dict): ...

    def confirm(self, user: dict, item_id: str) -> str: ...
    def claim(self, item_id: str | None = None) -> dict | None: ...
    def publish(self, job: dict, snapshot: Snapshot): ...
    def failed(self, job: dict, error: str, retry: bool): ...
    def remove(self, item_id: str): ...
    def recover(self): ...
    def schedule_shared(self, item_id: str, days: int): ...
    def schedule_private(self, user_id: int, item_id: str, days: int): ...
    def retry_shared(self, item_id: str): ...
    def rename_shared(self, item_id: str, name: str | None): ...


class ImportCatalog(Protocol):
    def read(self, item_id: str, kind: str | None = None) -> dict: ...


class ImportLibrary(Protocol):
    def decorate(self, user_id: int, document): ...

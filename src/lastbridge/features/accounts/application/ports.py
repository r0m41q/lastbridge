from typing import Protocol


class Cipher(Protocol):
    def encrypt(self, value: str) -> str: ...
    def decrypt(self, value: str) -> str: ...


class AccountStore(Protocol):
    def user(self, username: str) -> dict | None: ...
    def create_user(self, username: str, encoded: str, bootstrap: bool): ...
    def reset_password(self, username: str, encoded: str): ...
    def allow_login(self, scopes: tuple, now: int) -> bool: ...

    def create_session(
        self,
        user_id: int,
        encoded: str,
        token_hash: str,
        csrf: str,
        now: int,
        expiry: int,
    ) -> bool: ...
    def session(self, token_hash: str, now: int) -> dict | None: ...
    def logout(self, token_hash: str): ...

    def rotate_client_secret(
        self, user_id: int, encrypted: str, lookup: str
    ): ...
    def client_lookup(self, lookup: str) -> dict | None: ...
    def start_link(self, state_hash: str, session_hash: str, now: int): ...

    def claim_link(
        self, state_hash: str, token_hash: str, session_hash: str, now: int
    ) -> bool: ...

    def finish_link(
        self, session_hash: str, name: str, encrypted: str, now: int
    ) -> bool: ...
    def mark_relink(self, user_id: int): ...

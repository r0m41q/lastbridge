from typing import Protocol

from lastbridge.features.discovery.domain.models import TasteSample


class CatalogAccess(Protocol):
    def read(self, item_id: str, kind: str | None = None) -> dict: ...
    async def detail(self, item_id: str, kind: str) -> dict: ...
    async def match_loved(self, artist: str, title: str) -> dict: ...


class LibraryAccess(Protocol):
    def decorate(self, user_id: int, document): ...


class TasteProvider(Protocol):
    @property
    def configured(self) -> bool: ...

    async def taste_rows(
        self, method: str, **parameters
    ) -> list[tuple[str, str]]: ...


class MixStore(Protocol):
    def linked(self, user_id: int) -> bool | None: ...
    def touch(self, user_id: int) -> bool: ...
    def request(self, user_id: int): ...
    def status(self, user_id: int) -> dict | None: ...
    def user(self, user_id: int) -> dict | None: ...
    def local(self, user_id: int, target: str) -> TasteSample: ...
    def startup(self, refresh_interval: float) -> list[int]: ...
    def claim(self, inactive_ttl: float) -> dict | None: ...
    def failed(self, job: dict): ...

    def publish(
        self, job: dict, profile: dict, snapshot: dict, refresh_interval: float
    ): ...
    def recover(self): ...

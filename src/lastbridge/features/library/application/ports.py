from typing import Protocol


class CatalogAccess(Protocol):
    def read(self, item_id: str, kind: str | None = None) -> dict: ...
    async def detail(self, item_id: str, kind: str) -> dict: ...


class AudioStorage(Protocol):
    entries: dict

    async def update_pins(self, keys: set[str]): ...

    async def acquire(
        self, source: str, role: str = "stream", *, background: bool = False
    ) -> tuple[str, dict]: ...
    async def retain(self, key: str) -> bool: ...
    async def release(self, key: str): ...


class LibraryStore(Protocol):
    def sources(self) -> set[str]: ...
    def stars(self, user_id: int) -> dict: ...
    def plays(self, user_id: int) -> dict: ...

    def album_history(
        self, user_id: int, kind: str, size: int, offset: int
    ) -> list[dict]: ...
    def change(self, user_id, prepared, enabled, imported, now) -> bool: ...
    def reconcile(self, sources, saved_keys, startup=False): ...
    def claim(self) -> dict | None: ...
    def complete(self, source: str): ...
    def failed(self, source: str, attempts: int, message: str): ...
    def next_due(self) -> float | None: ...
    def retry(self, user_id: int): ...
    def downloads(self, user_id: int) -> list[dict]: ...
    def collection_ids(self, user_id: int, starred_only: bool) -> set[str]: ...
